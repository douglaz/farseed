use tau_relay::policy::Policy;

#[test]
fn independent_required_exclusions() {
    let policy = Policy::default();
    // This inventory is independent of the runtime tables: deleting a required
    // range must leave a failing fixture rather than delete its own regression.
    for (first, interior, last) in [
        ("0.0.0.0", "0.1.2.3", "0.255.255.255"),
        ("10.0.0.0", "10.23.45.67", "10.255.255.255"),
        ("100.64.0.0", "100.100.1.1", "100.127.255.255"),
        ("127.0.0.0", "127.0.0.1", "127.255.255.255"),
        ("169.254.0.0", "169.254.169.254", "169.254.255.255"),
        ("172.16.0.0", "172.20.1.1", "172.31.255.255"),
        ("192.0.0.0", "192.0.0.9", "192.0.0.255"),
        ("192.0.2.0", "192.0.2.5", "192.0.2.255"),
        ("192.31.196.0", "192.31.196.5", "192.31.196.255"),
        ("192.52.193.0", "192.52.193.5", "192.52.193.255"),
        ("192.88.99.0", "192.88.99.5", "192.88.99.255"),
        ("192.168.0.0", "192.168.2.3", "192.168.255.255"),
        ("192.175.48.0", "192.175.48.5", "192.175.48.255"),
        ("198.18.0.0", "198.19.2.3", "198.19.255.255"),
        ("198.51.100.0", "198.51.100.5", "198.51.100.255"),
        ("203.0.113.0", "203.0.113.5", "203.0.113.255"),
        ("224.0.0.0", "239.2.3.4", "239.255.255.255"),
        ("240.0.0.0", "250.1.2.3", "255.255.255.255"),
        (
            "2001::",
            "2001:123::1",
            "2001:1ff:ffff:ffff:ffff:ffff:ffff:ffff",
        ),
        (
            "2001:db8::",
            "2001:db8:1234::1",
            "2001:db8:ffff:ffff:ffff:ffff:ffff:ffff",
        ),
        (
            "2002::",
            "2002:808:808::1",
            "2002:ffff:ffff:ffff:ffff:ffff:ffff:ffff",
        ),
        (
            "2620:4f:8000::",
            "2620:4f:8000:1234::1",
            "2620:4f:8000:ffff:ffff:ffff:ffff:ffff",
        ),
        (
            "3fff::",
            "3fff:a00::1",
            "3fff:fff:ffff:ffff:ffff:ffff:ffff:ffff",
        ),
    ] {
        for text in [first, interior, last] {
            let ip = text.parse().unwrap();
            assert!(!policy.admits(ip), "admitted {text}");
            assert!(policy.select(&[ip], 443).is_none(), "selected {text}");
        }
    }
    for text in [
        "::",
        "::1",
        "::ffff:8.8.8.8",
        "::808:808",
        "64:ff9b::808:808",
        "64:ff9b:1::808:808",
        "100::1",
        "100:0:0:1::1",
        "2001::1234",
        "2001:10::1",
        "2001:20::1",
        "2001:30::1",
        "5f00::1",
        "fc00::1",
        "fd00::1",
        "fe80::1",
        "ff00::1",
        "ff02::1",
        "4000::1",
        "1fff:ffff::1",
    ] {
        assert!(!policy.admits(text.parse().unwrap()), "admitted {text}");
    }
    for text in [
        "9.0.0.1",
        "11.0.0.1",
        "100.63.255.255",
        "100.128.0.0",
        "172.15.255.255",
        "172.32.0.0",
        "198.17.255.255",
        "198.20.0.0",
        "2001:4860:4860::8888",
        "2606:4700::1111",
        "3ffe:ffff::1",
        "3fff:1000::1",
    ] {
        assert!(policy.admits(text.parse().unwrap()), "refused {text}");
    }
}
